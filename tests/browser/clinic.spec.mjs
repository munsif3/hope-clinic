import { test, expect } from '@playwright/test';

test('registration, booking, recovery, reviewed save, print privacy and phone lookup', async ({ page, context }, testInfo) => {
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    // All clinical writes are confined to the loopback demo. No real records.
    await context.route('**/*', route => {
        const url = new URL(route.request().url());
        return ['127.0.0.1', 'localhost'].includes(url.hostname) ? route.continue() : route.abort();
    });
    const date = new Date(Date.UTC(2040, 0, 1) + Math.floor(Math.random() * 200000) * 86400000).toISOString().slice(0, 10);
    await page.clock.install({ time: new Date(date + 'T04:30:00Z') });
    const patientName = `Synthetic browser ${Date.now()} ${testInfo.repeatEachIndex}`;
    await page.goto('/today');
    await expect(page).toHaveURL(/\/login$/);
    await page.getByLabel('Email Address', { exact: true }).fill('doctor@example.test');
    await page.getByLabel('Password', { exact: true }).fill('Synthetic-test-password-123');
    await page.getByRole('button', { name: 'Log In', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Today', exact: true })).toBeVisible();
    await expect(page.getByText('Local demo — synthetic records only.', { exact: false })).toBeVisible();
    await page.getByRole('button', { name: 'Open session', exact: true }).click();
    await expect(page.locator('summary').filter({ hasText: 'Clinic hours · 1 open sessions' })).toBeVisible();

    await page.goto('/patients/new?next=booking&date=' + date);
    await page.getByLabel('Full name', { exact: true }).fill(patientName);
    await page.getByLabel('Age', { exact: true }).fill('42');
    await page.getByLabel('Contact number', { exact: true }).fill('000' + Date.now());
    await page.getByRole('button', { name: 'Save & book appointment', exact: true }).click();
    const booking = page.getByRole('region', { name: 'Book an appointment', exact: true });
    await expect(booking.getByText(patientName, { exact: true })).toBeVisible();
    await booking.getByRole('radio', { name: '10:30–11:00', exact: true }).check();
    await booking.getByRole('button', { name: 'Confirm appointment', exact: true }).click();
    await expect(booking).toHaveCount(0);
    await page.getByRole('button', { name: 'Reschedule', exact: true }).click();
    await page.getByRole('radio', { name: '11:00–11:30', exact: true }).check();
    await page.getByRole('button', { name: 'Confirm new time', exact: true }).click();
    await expect(page.getByRole('region', { name: 'Reschedule appointment', exact: true })).toHaveCount(0);
    await page.getByRole('button', { name: 'Mark arrived', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Mark arrived', exact: true })).toHaveCount(0);
    await page.getByRole('button', { name: 'Start consultation', exact: true }).click();
    await expect(page).toHaveURL(/appointmentId=/);
    const consultationURL = page.url();
    await page.locator('#diagnosis').fill('Synthetic browser assessment');
    await page.locator('summary').filter({ hasText: 'Private clinical notes' }).click();
    await page.locator('#notes').fill('PRIVATE SYNTHETIC BROWSER NOTE');
    await page.locator('#patientInstructions').fill('Synthetic handout instructions');
    await page.getByRole('button', { name: 'Add Prescription', exact: true }).click();
    await page.getByLabel('Medication', { exact: true }).fill('Synthetic browser medicine');
    await page.getByLabel('Dosage', { exact: true }).fill('Fixture dose');
    await page.getByLabel('Frequency', { exact: true }).fill('Fixture frequency');
    await page.getByLabel('Duration', { exact: true }).fill('Fixture duration');
    await page.getByRole('link', { name: 'Return to Today', exact: true }).click();
    await page.getByRole('button', { name: 'Resume consultation', exact: true }).click();
    await expect(page).toHaveURL(consultationURL);
    await page.getByRole('button', { name: 'Restore draft', exact: true }).click();
    await expect(page.locator('#diagnosis')).toHaveValue('Synthetic browser assessment');
    await expect(page.locator('#notes')).toHaveValue('PRIVATE SYNTHETIC BROWSER NOTE');
    await page.getByRole('button', { name: 'Review & save', exact: true }).click();
    const review = page.getByRole('dialog', { name: 'Review consultation' });
    await expect(review).toBeVisible();
    await review.getByRole('button', { name: 'Save visit record', exact: true }).click();
    await expect(review).toBeVisible(); // Required treatment review must block submission.
    await review.getByRole('checkbox').check();
    await review.getByRole('button', { name: 'Save visit record', exact: true }).click();
    await expect(page).toHaveURL(/\/patients\/[^/?]+$/);
    const patientURL = page.url();
    await expect(page.getByRole('link', { name: 'Print Visit', exact: true })).toHaveCount(1);
    await page.getByRole('link', { name: 'Print Visit', exact: true }).click();
    await expect(page.getByText('Synthetic handout instructions', { exact: true })).toBeVisible();
    await expect(page.getByText('PRIVATE SYNTHETIC BROWSER NOTE', { exact: true })).toHaveCount(0);
    await page.emulateMedia({ media: 'print' });
    await expect(page.getByRole('button', { name: 'Print visit', exact: true })).toBeHidden();
    await page.emulateMedia({ media: 'screen' });
    await page.goto('/today');
    await page.locator('summary').filter({ hasText: 'Completed and closed appointments (1)' }).click();
    await expect(page.getByRole('link', { name: 'Open saved visit', exact: true })).toBeVisible();
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
    await page.goto(patientURL);
    await expect(page.getByRole('heading', { name: patientName, exact: true })).toBeVisible();
    await expect(page.getByRole('link', { name: 'Book a return', exact: true })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
    await page.getByRole('button', { name: 'Open navigation', exact: true }).click();
    await page.getByRole('button', { name: 'Sign Out', exact: true }).click();
    await expect(page).toHaveURL(/\/login$/);
    await page.goto(patientURL);
    await expect(page).toHaveURL(/\/login$/);
    expect(errors).toEqual([]);
});
